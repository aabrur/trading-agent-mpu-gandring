// Actual archive API + built Office UI, using only synthetic PAPER data and disposable services.
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { AddressInfo } from 'node:net';
import { SessionLogger } from '../server/session-log.js';
import { createApp } from '../server/app.js';
import { loadConfig } from '../server/config.js';
import { registerSecrets } from '../server/redact.js';

const output = path.resolve(process.env.SESSION_CHECK_OUTPUT ?? 'data/logs/verification');
await mkdir(output, { recursive: true });
const root = path.resolve('data/logs/sessions');
const previous = await SessionLogger.start({ root, entrypoint: 'verification:previous', version: '0.0.0.4.0' });
previous.updateContext({ mode: 'PAPER', appMode: 'LOCAL', providers: { lead: { provider: 'mock', model: 'synthetic' } } });
previous.write({ source: 'fixture', eventName: 'fixture.previous', message: 'Synthetic earlier session retained', details: { synthetic: true } });
await previous.finish('CLEAN_SHUTDOWN', 'Synthetic earlier run completed');
const logger = await SessionLogger.start({ root, entrypoint: 'verification:office', version: '0.0.0.4.0' });
logger.updateContext({ mode: 'PAPER', appMode: 'LOCAL', providers: { lead: { provider: 'mock', model: 'synthetic' } } });
const secret = 'synthetic-session-verification-secret';
registerSecrets([secret]);
for (let i = 0; i < 230; i++) logger.write({ source: 'fixture', eventName: 'fixture.sample', level: i === 0 ? 'WARN' : 'INFO', message: i === 0 ? `Synthetic earliest marker ${secret}` : `Synthetic sample ${i}`, correlationId: 'synthetic-decision-1', details: { synthetic: true, index: i } });
await logger.flush();
const cfg = loadConfig({ TRADING_MODE: 'PAPER', DEFAULT_PROVIDER: 'mock', MARKET_SOURCE: 'sample', AUTO_TRADING: 'off' });
const built = createApp(cfg, { sessionLog: logger, reportsDir: null, learningsPath: null, conversationsPath: null, jevEnv: {}, killFile: null });
await new Promise<void>(resolve => built.server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${(built.server.address() as AddressInfo).port}`;
const executablePath = [process.env.CHROME_PATH, 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'].find(file => file && existsSync(file));
assert(executablePath, 'Set CHROME_PATH to a Chromium browser');
const browser = await chromium.launch({ executablePath, headless: true });
const errors: string[] = [];
let verified = false;
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
try {
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => {
    const url = new URL(route.request().url());
    if (url.origin !== base) return route.abort();
    if (!url.pathname.startsWith('/api/') || url.pathname.startsWith('/api/logs/sessions') || url.pathname === '/api/state' || url.pathname === '/api/health' || url.pathname === '/api/logs/client') return route.continue();
    const body = url.pathname === '/api/candles' ? { symbol: 'BTCUSDT', source: 'sample', example: true, last: 100, change24hPct: 0, candles: [] } : { ok: true, available: false, venues: [], killed: false };
    return route.fulfill({ contentType: 'application/json', body: JSON.stringify(body) });
  });
  await page.goto(base);
  await page.waitForSelector('.office');
  for (const selector of ['.tour-skip-btn', '.trakteer-close-x']) if (await page.locator(selector).isVisible()) await page.locator(selector).click();
  await page.locator('#tool-log').click();
  await page.getByRole('button', { name: 'Archived sessions', exact: true }).click();
  await page.getByLabel('Choose archived session').selectOption(logger.session.sessionId);
  await page.getByText('Synthetic sample 229', { exact: true }).waitFor();
  const pageCount = await page.locator('.session-event').count();
  assert.equal(pageCount, 100);
  await page.getByRole('button', { name: 'Older events', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.session-event').length === 200);
  await page.getByRole('button', { name: 'Older events', exact: true }).click();
  await page.getByText('Synthetic earliest marker [REDACTED]', { exact: true }).waitFor();
  await page.locator('.session-filters select').selectOption('WARN');
  await page.locator('.session-filters input').nth(0).fill('fixture');
  await page.locator('.session-filters input').nth(1).fill('earliest marker');
  await page.waitForFunction(() => document.querySelectorAll('.session-event').length === 1);
  await page.getByRole('button', { name: 'synthetic-decision-1', exact: true }).click();
  await page.waitForFunction(() => document.querySelector<HTMLInputElement>('.session-filters label:last-child input')?.value === 'synthetic-decision-1');
  const downloadEvent = page.waitForEvent('download');
  await page.locator('.session-downloads a').filter({ hasText: /^events$/ }).click();
  const download = await downloadEvent;
  const exportFile = path.join(output, 'selected-session.jsonl');
  await download.saveAs(exportFile);
  const exported = await readFile(exportFile, 'utf8');
  assert(!exported.includes(secret)); assert(exported.includes('fixture.sample'));
  await page.screenshot({ path: path.join(output, 'archive-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'No mobile page overflow');
  assert(await page.locator('.session-filters').evaluate(element => element.scrollWidth <= element.clientWidth + 1), 'No filter overflow');
  await page.screenshot({ path: path.join(output, 'archive-mobile.png') });
  await page.getByLabel('Choose archived session').selectOption(previous.session.sessionId);
  await page.locator('.session-filters select').selectOption('');
  await page.locator('.session-filters input').nth(0).fill('');
  await page.locator('.session-filters input').nth(1).fill('');
  await page.locator('.session-filters input').nth(2).fill('');
  await page.getByText('Synthetic earlier session retained', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Live', exact: true }).click();
  built.desk.recordActivity({ kind: 'backend', source: 'fixture', level: 'info', text: 'Synthetic live UI event' });
  await page.getByText('Synthetic live UI event', { exact: true }).waitFor();
  await page.locator('#tool-history').click();
  assert.equal(await page.locator('select[aria-label="History filter"]').count(), 1);
  assert.deepEqual(errors, []);
  verified = true;
  console.log(JSON.stringify({ status: 'PASS', synthetic: true, activeSample: logger.session.sessionId, previousSample: previous.session.sessionId, output, browserErrors: errors.length }));
} catch (error) {
  await page.screenshot({ path: path.join(output, 'archive-failure.png') });
  await writeFile(path.join(output, 'browser-failure.txt'), JSON.stringify({ errors, text: await page.locator('body').innerText() }, null, 2));
  throw error;
} finally {
  await browser.close(); built.desk.stop(); await new Promise<void>(resolve => built.server.close(() => resolve()));
  await logger.finish(verified ? 'CLEAN_SHUTDOWN' : 'RUNTIME_ERROR', verified ? 'Synthetic Office verification passed' : 'Synthetic Office verification failed');
}
